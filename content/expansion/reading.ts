export const readingExpansion: Question[] = cases.flatMap((p, index) => {
  const text =
    p.intro +
    "\n\n" +
    p.details.map((d) => d[0]).join(" ") +
    "\n\n" +
    p.closing;
  const [main, ...otherTopics] = p.summary;
  const items: { topic: string; item: Item; evidence: string }[] = [
    {
      topic: "Main idea",
      item: [
        "What is the passage mainly about?",
        main,
        ...otherTopics,
        `Gagasan utamanya adalah ${main.toLowerCase()}. Pembukaan dan penutup membahas proyek yang sama: ${p.intro} ${p.closing}`,
      ] as Item,
      evidence: p.intro + " " + p.closing,
    },
  ];
  for (const [sentence, prompt, right, a, b, c] of p.details)
    items.push({
      topic: /refer/.test(prompt) ? "Reference" : "Supporting details",
      item: [
        prompt,
        right,
        a,
        b,
        c,
        `Jawaban “${right}” sesuai informasi eksplisit: ${sentence}`,
      ],
      evidence: sentence,
    });
  const [word, meaning, a, b, c] = p.vocabulary;
  const evidence = [p.intro, ...p.details.map((d) => d[0]), p.closing].find(
    (t) => t.toLowerCase().includes(word.toLowerCase()),
  );
  if (!evidence) throw new Error(`Vocabulary missing from ${p.title}: ${word}`);
  items.push({
    topic: "Vocabulary in context",
    item: [
      `The word “${word}” in the passage is closest in meaning to ...`,
      meaning,
      a,
      b,
      c,
      `Dalam konteks “${evidence}”, ${word} berarti “${meaning.toLowerCase()}”.`,
    ],
    evidence,
  });
  items.push({ topic: "Inference", item: p.inference, evidence: p.closing });
  items.push({
    topic: "Author’s purpose",
    item: [
      "What is the author’s main purpose?",
      `To explain ${main.toLowerCase()}`,
      `To promote ${otherTopics[0].toLowerCase()}`,
      `To provide instructions for ${otherTopics[1].toLowerCase()}`,
      `To narrate a personal holiday involving ${otherTopics[2].toLowerCase()}`,
      `Penulis menjelaskan ${main.toLowerCase()} melalui alasan, cara kerja, hasil, serta batasannya; teks bukan promosi atau cerita liburan.`,
    ],
    evidence: p.intro + " " + p.closing,
  });
  if (items.length !== 10)
    throw new Error(`Expected ten questions: ${p.title}`);
  return items.map(({ topic, item, evidence }, j) => {
    const q = make(
      `reading-${51 + index * 10 + j}`,
      "reading",
      "reading",
      topic,
      item,
    );
    return {
      ...q,
      passage: { id: `passage-${index + 6}`, title: p.title, text },
      explanation: { ...q.explanation, evidence },
    };
  });
});
